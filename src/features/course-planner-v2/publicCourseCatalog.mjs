function mirrorMeta(course) {
  return {
    ...course,
    id: `${course.id}_mirror`,
    title: `${course.title} · spegel`,
    description: `${course.description} Spegelvänd över banans mittlinje för träning från motsatt handlingssida.`,
    focus: [...course.focus, "spegelträning"],
    isMirror: true,
    sourceId: course.id,
  };
}

export const PUBLIC_COURSE_CATALOG = [
  ...BASE_COURSES.map((course) => ({ ...course, isMirror: false, sourceId: null })),
  ...BASE_COURSES.filter((course) => course.mirrorable).map(mirrorMeta),
].map(({ mirrorable: _mirrorable, ...course }) => course);

