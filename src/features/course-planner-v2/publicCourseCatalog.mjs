export function resolvePublicCourseId(courseId) {
  if (!courseId) return null;
  return LEGACY_COURSE_ALIASES[courseId] ?? courseId;
}

export function getPublicCourseMeta(courseId) {
  const resolved = resolvePublicCourseId(courseId);
  return PUBLIC_COURSE_CATALOG.find((course) => course.id === resolved);
}
